import { readFile, writeFile } from 'node:fs/promises';

const textures = [
  ['parquetImage', 'herringbone_parquet_diff_1k.jpg'],
  ['stoneImage', 'marble_01_diff_1k.jpg'],
];

const exports = await Promise.all(textures.map(async ([name, filename]) => {
  const image = await readFile(new URL(`../assets/${filename}`, import.meta.url));
  const dataUrl = `data:image/jpeg;base64,${image.toString('base64')}`;
  return `export const ${name} = ${JSON.stringify(dataUrl)};`;
}));

let floorPlanImage = null;
try {
  const image = await readFile(new URL('../assets/original-plan.jpg', import.meta.url));
  floorPlanImage = `data:image/jpeg;base64,${image.toString('base64')}`;
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
exports.push(`export const floorPlanImage = ${JSON.stringify(floorPlanImage)};`);

await writeFile(
  new URL('../src/textures.js', import.meta.url),
  '// Generated by scripts/embed-textures.mjs. Do not edit.\n' + exports.join('\n') + '\n',
);
console.log(`Embedded ${textures.length} textures for offline viewing.`);
